# ---------------------------------------------------------------------------
# LLM judge
# ---------------------------------------------------------------------------

def judge_generation(
    *,
    question: str,
    expected_answer: str,
    generated_answer: str,
    context: str,
) -> dict[str, float]:

    judge_prompt = f"""
You are evaluating an enterprise RAG response.

Question:
{question}

Reference answer:
{expected_answer}

Retrieved context:
{context}

Generated answer:
{generated_answer}

Evaluate two properties.

1. correctness
Does the generated answer correctly answer the question
and agree with the reference answer?

2. faithfulness
Are the factual claims made by the generated answer
supported by the retrieved context?

Use scores between 0 and 1.

Return ONLY valid JSON in this exact structure:

{{
  "correctness": 0.0,
  "faithfulness": 0.0
}}
"""

    response = judge_model.invoke(
        judge_prompt
    )

    content = str(
        response.content
    ).strip()

    if content.startswith(
        "```"
    ):

        content = (
            content
            .replace(
                "```json",
                "",
            )
            .replace(
                "```",
                "",
            )
            .strip()
        )

    result = json.loads(
        content
    )

    return {
        "correctness": float(
            result["correctness"]
        ),
        "faithfulness": float(
            result["faithfulness"]
        ),
    }


def answer_correctness_evaluator(
    run,
    example,
):

    test_type = str(
        reference_value(
            example,
            "test_type",
            "",
        )
    )

    if test_type not in {
        "retrieval_and_generation",
        "generation",
        "multi_hop_generation",
        "ambiguity",
    }:

        return {
            "key": "answer_correctness",
            "score": None,
        }

    question = str(
        run.inputs.get(
            "question",
            "",
        )
    )

    expected_answer = str(
        reference_value(
            example,
            "expected_answer",
            "",
        )
    )

    generated_answer = str(
        run.outputs.get(
            "answer",
            "",
        )
    )

    context = str(
        run.outputs.get(
            "context",
            "",
        )
    )

    scores = judge_generation(
        question=question,
        expected_answer=expected_answer,
        generated_answer=generated_answer,
        context=context,
    )

    return {
        "key": "answer_correctness",
        "score": scores[
            "correctness"
        ],
    }


