def parse_semicolon_field(
    value: Any,
) -> list[str]:

    if value is None:
        return []

    if isinstance(value, list):
        return [
            str(item).strip()
            for item in value
            if str(item).strip()
        ]

    value = str(value).strip()

    if not value:
        return []

    return [
        item.strip()
        for item in value.split(";")
        if item.strip()
    ]


def normalize_page(
    value: Any,
) -> str:

    if value is None:
        return ""

    if isinstance(
        value,
        float,
    ) and value.is_integer():
        return str(
            int(value)
        )

    return str(
        value
    ).strip()


def format_context(
    documents: list[Document],
) -> str:

    return "\n\n---\n\n".join(
        (
            f"[Source: "
            f"{document.metadata.get('document_id')} | "
            f"Page: "
            f"{normalize_page(document.metadata.get('page_number'))}]"
            f"\n{document.page_content}"
        )
        for document in documents
    )


# ---------------------------------------------------------------------------
# Citation parser
#
# Parses citations generated by your prompt:
#
# [SEC-004, page 1]
# ---------------------------------------------------------------------------

CITATION_PATTERN = re.compile(
    r"\[([A-Za-z0-9_-]+),\s*page\s+(\d+)\]",
    re.IGNORECASE,
)


def parse_answer_citations(
    answer: str,
) -> list[tuple[str, str]]:

    matches = (
        CITATION_PATTERN.findall(
            answer
        )
    )

    return [
        (
            document_id.strip(),
            page.strip(),
        )
        for document_id, page in matches
    ]


