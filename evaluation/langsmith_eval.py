def mrr_evaluator(
    run,
    example,
):

    if not reference_value(
        example,
        "answerable",
        False,
    ):
        return {
            "key": "mrr",
            "score": None,
        }

    expected = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_source_documents",
                "",
            )
        )
    )

    retrieved = (
        run.outputs.get(
            "retrieved_documents",
            []
        )
    )

    reciprocal_rank = 0.0

    for rank, document_id in enumerate(
        retrieved,
        start=1,
    ):

        if document_id in expected:

            reciprocal_rank = (
                1.0 / rank
            )

            break

    return {
        "key": "mrr",
        "score": reciprocal_rank,
    }


def page_hit_evaluator(
    run,
    example,
):

    if not reference_value(
        example,
        "answerable",
        False,
    ):
        return {
            "key": "page_hit",
            "score": None,
        }

    expected_documents = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_source_documents",
                "",
            )
        )
    )

    expected_pages = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_page",
                "",
            )
        )
    )

    retrieved_results = (
        run.outputs.get(
            "retrieved_results",
            []
        )
    )

    score = 0

    for result in retrieved_results:

        if (
            result["document_id"]
            in expected_documents
            and result["page_number"]
            in expected_pages
        ):
            score = 1
            break

    return {
        "key": "page_hit",
        "score": score,
    }


# ---------------------------------------------------------------------------
# RBAC evaluator
# ---------------------------------------------------------------------------

def rbac_evaluator(
    run,
    example,
):

    test_type = str(
        reference_value(
            example,
            "test_type",
            "",
        )
    )

    if (
        test_type
        != "rbac_unauthorized"
    ):
        return {
            "key": "rbac_protection",
            "score": None,
        }

    restricted_documents = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_source_documents",
                "",
            )
        )
    )

    retrieved = set(
        run.outputs.get(
            "retrieved_documents",
            []
        )
    )

    leaked = bool(
        restricted_documents
        & retrieved
    )

    return {
        "key": "rbac_protection",
        "score": (
            0
            if leaked
            else 1
        ),
    }


# ---------------------------------------------------------------------------
# No-answer evaluator
# ---------------------------------------------------------------------------

def no_answer_evaluator(
    run,
    example,
):

    test_type = str(
        reference_value(
            example,
            "test_type",
            "",
        )
    )

    if test_type != "no_answer":
        return {
            "key": "no_answer_correct",
            "score": None,
        }

    answer = str(
        run.outputs.get(
            "answer",
            "",
        )
    ).strip()

    citations = (
        run.outputs.get(
            "citations",
            []
        )
    )

    correct = (
        answer == NO_ANSWER
        and len(citations) == 0
    )

    return {
        "key": "no_answer_correct",
        "score": int(correct),
    }


