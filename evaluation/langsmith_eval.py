def no_answer_evaluator(
    run,
    example,
):

    test_type = str(
        reference_value(
            example,
            "test_type",
            "",
        )
    )

    if test_type != "no_answer":
        return {
            "key": "no_answer_correct",
            "score": None,
        }

    answer = str(
        run.outputs.get(
            "answer",
            "",
        )
    ).strip()

    citations = (
        run.outputs.get(
            "citations",
            []
        )
    )

    correct = (
        answer == NO_ANSWER
        and len(citations) == 0
    )

    return {
        "key": "no_answer_correct",
        "score": int(correct),
    }


