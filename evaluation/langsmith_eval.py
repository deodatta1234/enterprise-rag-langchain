def hit_at_1_evaluator(
    run,
    example,
):

    if not reference_value(
        example,
        "answerable",
        False,
    ):
        return {
            "key": "hit_at_1",
            "score": None,
        }

    expected = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_source_documents",
                "",
            )
        )
    )

    retrieved = (
        run.outputs.get(
            "retrieved_documents",
            []
        )
    )

    score = int(
        bool(
            retrieved
            and retrieved[0] in expected
        )
    )

    return {
        "key": "hit_at_1",
        "score": score,
    }


