def reference_value(
    example,
    key: str,
    default: Any = None,
) -> Any:
    """
    Read a value from LangSmith reference outputs first,
    then metadata.

    This makes the script slightly more tolerant of how
    the dataset was created.
    """

    outputs = (
        example.outputs
        or {}
    )

    metadata = (
        example.metadata
        or {}
    )

    if key in outputs:
        return outputs[key]

    return metadata.get(
        key,
        default,
    )


