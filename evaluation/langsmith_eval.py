# RBAC evaluator
# ---------------------------------------------------------------------------

def rbac_evaluator(
    run,
    example,
):

    test_type = str(
        reference_value(
            example,
            "test_type",
            "",
        )
    )

    if (
        test_type
        != "rbac_unauthorized"
    ):
        return {
            "key": "rbac_protection",
            "score": None,
        }

    restricted_documents = set(
        parse_semicolon_field(
            reference_value(
                example,
                "expected_source_documents",
                "",
            )
        )
    )

    retrieved = set(
        run.outputs.get(
            "retrieved_documents",
            []
        )
    )

    leaked = bool(
        restricted_documents
        & retrieved
    )

    return {
        "key": "rbac_protection",
        "score": (
            0
            if leaked
            else 1
        ),
    }


