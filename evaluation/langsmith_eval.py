# ---------------------------------------------------------------------------
# Run LangSmith experiment
# ---------------------------------------------------------------------------

def main() -> None:

    client = Client()

    print(
        f"Running LangSmith experiment "
        f"on dataset: {DATASET_NAME}"
    )

    try:

        results = client.evaluate(
            target,
            data=DATASET_NAME,

            evaluators=[
                # Retrieval
                hit_at_1_evaluator,
                hit_at_3_evaluator,
                hit_at_5_evaluator,
                mrr_evaluator,
                page_hit_evaluator,

                # Security / robustness
                rbac_evaluator,
                no_answer_evaluator,

                # Generation citations
                citation_document_evaluator,
                citation_page_evaluator,

                # LLM-as-a-judge
                answer_correctness_evaluator,
                faithfulness_evaluator,

                # Performance
                retrieval_latency_evaluator,
                total_latency_evaluator,
            ],

            experiment_prefix=(
                EXPERIMENT_PREFIX
            ),

            description=(
                "Enterprise Chain RAG evaluation: "
                "retrieval, RBAC, no-answer, "
                "generation quality, citations "
                "and performance."
            ),

            # Start sequentially.
            # This is easier on OpenAI/Weaviate rate limits.
            max_concurrency=0,

            metadata={
                "retrieval_k": (
                    RETRIEVAL_K
                ),
                "collection": (
                    settings.collection_name
                ),
                "chat_model": (
                    settings.chat_model
                ),
            },
        )

        print()
        print(
            "LangSmith experiment complete."
        )

        # ExperimentResults exposes experiment metadata/results.
        print(
            results
        )

    finally:

        weaviate_client.close()


if __name__ == "__main__":
    main()