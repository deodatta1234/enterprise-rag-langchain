# ---------------------------------------------------------------------------
# LangSmith target
# ---------------------------------------------------------------------------

def target(
    inputs: dict,
) -> dict:
    """
    This function represents the complete RAG application
    that LangSmith evaluates.

    LangSmith calls this once for every dataset example.
    """

    question = str(
        inputs["question"]
    ).strip()

    user_groups = parse_semicolon_field(
        inputs.get(
            "user_groups"
        )
        or inputs.get(
            "allowed_user_roles_groups"
        )
    )

    # -------------------------------------------------------
    # Retrieval
    # -------------------------------------------------------

    retrieval_start = (
        time.perf_counter()
    )

    documents = (
        retrieve_documents_with_resources(
            question=question,
            user_groups=user_groups,
            client=weaviate_client,
            embeddings=embeddings,
            collection_name=(
                settings.collection_name
            ),
            k=RETRIEVAL_K,
            settings=settings,
        )
    )

    retrieval_latency_ms = (
        time.perf_counter()
        - retrieval_start
    ) * 1000

    # -------------------------------------------------------
    # Generation
    # -------------------------------------------------------

    context = format_context(
        documents
    )

    total_start = (
        time.perf_counter()
    )

    if not documents:

        answer = NO_ANSWER

    else:

        answer = generation_chain.invoke(
            {
                "question": question,
                "context": context,
            }
        ).strip()

    # retrieval + generation
    total_rag_latency_ms = (
        retrieval_latency_ms
        +
        (
            (
                time.perf_counter()
                - total_start
            )
            * 1000
        )
    )

    # -------------------------------------------------------
    # Retrieved metadata
    # -------------------------------------------------------

    retrieved_documents = [
        str(
            document.metadata.get(
                "document_id",
                "",
            )
        )
        for document in documents
    ]

    retrieved_pages = [
        normalize_page(
            document.metadata.get(
                "page_number"
            )
        )
        for document in documents
    ]

    retrieved_results = [
        {
            "document_id": str(
                document.metadata.get(
                    "document_id",
                    "",
                )
            ),
            "page_number": normalize_page(
                document.metadata.get(
                    "page_number"
                )
            ),
            "retrieval_rank": document.metadata.get("retrieval_rank"),
            "hybrid_score": document.metadata.get("hybrid_score"),
            "rerank_score": document.metadata.get("rerank_score"),
        }
        for document in documents
    ]

    # -------------------------------------------------------
    # Citations actually generated by the LLM
    # -------------------------------------------------------

    citations = (
        parse_answer_citations(
            answer
        )
    )

    # Important:
    # no-answer responses should have no citations.

    if answer == NO_ANSWER:
        citations = []

    return {
        "answer": answer,

        "retrieved_documents": (
            retrieved_documents
        ),

        "retrieved_pages": (
            retrieved_pages
        ),

        "retrieved_results": (
            retrieved_results
        ),

        "citations": [
            {
                "document_id": doc_id,
                "page_number": page,
            }
            for doc_id, page in citations
        ],

        "context": context,

        "retrieval_latency_ms": (
            retrieval_latency_ms
        ),

        "total_rag_latency_ms": (
            total_rag_latency_ms
        ),
    }


